const SPRACHEN: Record<string, Record<string, string>> = {
  de: {
    de: "Deutsch",
    en: "Englisch",
    fr: "Französisch",
    es: "Spanisch",
    it: "Italienisch",
    la: "Latein",
  },
  en: {
    de: "German",
    en: "English",
    fr: "French",
    es: "Spanish",
    it: "Italian",
    la: "Latin",
  },
};

export type Uebersetzer = (
  schluessel: Schluessel,
  werte?: Record<string, string | number>,
) => string;

function kurz(sprache: string): "de" | "en" {
  return sprache.toLowerCase().startsWith("de") ? "de" : "en";
}

export function uebersetzer(sprache: string): Uebersetzer {
  const tabelle = kurz(sprache) === "de" ? de : en;
  return (schluessel, werte = {}) =>
    tabelle[schluessel].replace(/\{(\w+)\}/g, (_, name: string) =>
      String(werte[name] ?? ""),
    );
}

export function sprachname(sprache: string, code: string): string {
  return SPRACHEN[kurz(sprache)]?.[code] ?? code;
}

/** Translate an error of the WebSocket API into a readable message. */
export function fehlertext(t: Uebersetzer, fehler: unknown): string {
  const err = fehler as { code?: string; message?: string } | undefined;
  const kandidaten = [`err_${err?.message ?? ""}`, `err_${err?.code ?? ""}`];
  for (const kandidat of kandidaten) {
    if (kandidat in de) {
      return t(kandidat as Schluessel);
    }
  }
  return t("fehler_allgemein", { fehler: err?.message ?? String(fehler) });
}
